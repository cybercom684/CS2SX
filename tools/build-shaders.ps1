# Compiles the runtime's GLSL shaders with deko3d's `uam` and embeds the binaries
# as C arrays in src/CS2SX/Runtime/cs2sx_gfx_shaders.h.
#
# Only needed after editing src/CS2SX/Runtime/shaders/*.glsl - the generated header
# is committed, so building cs2sx or an app does not require uam.
#
#   pwsh tools/build-shaders.ps1

$ErrorActionPreference = 'Stop'
$root    = Split-Path -Parent $PSScriptRoot
$runtime = Join-Path $root 'src/CS2SX/Runtime'
$dkp     = if ($env:DEVKITPRO) { $env:DEVKITPRO } else { 'C:/devkitPro' }
$uam     = Join-Path $dkp 'tools/bin/uam'
if (Test-Path "$uam.exe") { $uam = "$uam.exe" }

$shaders = @(
    @{ File = 'gfx2d_vsh.glsl'; Stage = 'vert'; Name = 'cs2sx_gfx2d_vsh' },
    @{ File = 'gfx2d_fsh.glsl'; Stage = 'frag'; Name = 'cs2sx_gfx2d_fsh' }
)

$tmp = Join-Path ([IO.Path]::GetTempPath()) ('cs2sx_shaders_' + [Guid]::NewGuid().ToString('N'))
New-Item -ItemType Directory $tmp | Out-Null
$out = [Text.StringBuilder]::new()
[void]$out.AppendLine('#pragma once')
[void]$out.AppendLine('// GENERATED by tools/build-shaders.ps1 from Runtime/shaders/*.glsl - do not edit.')
[void]$out.AppendLine('// deko3d shader binaries (.dksh), compiled with uam.')
[void]$out.AppendLine('')
try {
    foreach ($s in $shaders) {
        $src = Join-Path $runtime "shaders/$($s.File)"
        $bin = Join-Path $tmp "$($s.Name).dksh"
        & $uam -s $s.Stage -o $bin $src
        if ($LASTEXITCODE -ne 0) { throw "uam failed for $($s.File)" }
        $bytes = [IO.File]::ReadAllBytes($bin)
        [void]$out.AppendLine("static const unsigned char $($s.Name)[$($bytes.Length)] __attribute__((aligned(256))) = {")
        for ($i = 0; $i -lt $bytes.Length; $i += 16) {
            $line = ($bytes[$i..([Math]::Min($i + 15, $bytes.Length - 1))] | ForEach-Object { '0x{0:x2}' -f $_ }) -join ','
            [void]$out.AppendLine("    $line,")
        }
        [void]$out.AppendLine('};')
        [void]$out.AppendLine('')
    }
}
finally { Remove-Item $tmp -Recurse -Force }

$target = Join-Path $runtime 'cs2sx_gfx_shaders.h'
[IO.File]::WriteAllText($target, $out.ToString().Replace("`r`n", "`n"), [Text.UTF8Encoding]::new($false))
Write-Host "wrote $target"
