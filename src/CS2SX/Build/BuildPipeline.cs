    // FIX: "static" entfernt → Zugriff auf _projectDir möglich
    private void WriteForwardDeclarations(
        IReadOnlyList<string> sourceFiles,
        string outputPath,
        IEnumerable<string>? expandedTypeNames = null,
        IReadOnlySet<string>? listUserClassTypes = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#pragma once");
        sb.AppendLine("#include <setjmp.h>");
        // Runtime types + headers — shared with the runtime modules (rt_*.c).
        sb.AppendLine("#include \"cs2sx_prelude.h\"");
        sb.AppendLine();
        sb.AppendLine("// Nullable value types: T? → { T value; int has; }");
        foreach (var prim in CS2SX.Core.TypeRegistry.NullablePrimitives)
            sb.AppendLine(CS2SX.Core.TypeRegistry.NullableTypedef(prim));
        sb.AppendLine();

        var alreadyDeclared = new HashSet<string>(StringComparer.Ordinal)
        {
            "Control", "Form", "Label", "Button", "ProgressBar", "SwitchApp",
        };

        foreach (var csFile in sourceFiles)
        {
            var source = System.IO.File.ReadAllText(csFile);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            foreach (var typeDecl in tree.GetRoot()
                .DescendantNodes()
                .Where(n => n is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax))
            {
                if (typeDecl is TypeDeclarationSyntax generic
                    && generic.TypeParameterList?.Parameters.Count > 0)
                    continue;

                var typeName = ((TypeDeclarationSyntax)typeDecl).Identifier.Text;

                if (alreadyDeclared.Add(typeName))
                    sb.AppendLine($"typedef struct {typeName} {typeName};");

                // Also forward-declare the vtable struct for classes with virtual methods
                if (typeDecl is ClassDeclarationSyntax clsWithVirtuals
                    && Transpiler.VTableBuilder.HasVirtualMethods(clsWithVirtuals))
                    sb.AppendLine($"typedef struct {typeName}_vtable {typeName}_vtable;");
            }

            // Interfaces are value structs {vtable*, obj*} defined in _interfaces.h, but
            // List<IFace> etc. in _generics.h (included first) only need the name.
            foreach (var iface in tree.GetRoot().DescendantNodes().OfType<InterfaceDeclarationSyntax>())
            {
                if (iface.TypeParameterList?.Parameters.Count > 0) continue;
                var iName = iface.Identifier.Text;
                if (!alreadyDeclared.Add(iName)) continue;
                sb.AppendLine($"typedef struct {iName} {iName};");
                sb.AppendLine($"typedef struct {iName}_vtable {iName}_vtable;");
            }

            // User enums must be globally visible (other files use them as field /
            // parameter types). Emit the full definition here, in _forward.h, since
            // a C enum cannot be forward-declared. Per-file emission is suppressed.
            foreach (var en in tree.GetRoot().DescendantNodes().OfType<EnumDeclarationSyntax>())
            {
                var enName = en.Identifier.Text;
                if (!alreadyDeclared.Add("enum:" + enName)) continue;
                sb.AppendLine($"typedef enum {enName} {{");
                var enMembers = en.Members.Select(m => m.Identifier.Text).ToList();
                foreach (var m in en.Members)
                {
                    var cMember = CS2SX.Core.TypeRegistry.EnumMemberCName(enName, m.Identifier.Text);
                    if (m.EqualsValue != null)
                        sb.AppendLine($"    {cMember} = {CS2SX.Core.TypeRegistry.PrefixEnumValueExpr(enName, m.EqualsValue.Value.ToString(), enMembers)},");
                    else
                        sb.AppendLine($"    {cMember},");
                }
                sb.AppendLine($"}} {enName};");
                sb.AppendLine(CS2SX.Core.TypeRegistry.NullableTypedef(enName));
            }
        }

        if (expandedTypeNames != null)
        {
            var hadAny = false;
            foreach (var expandedName in expandedTypeNames)
            {
                if (!alreadyDeclared.Add(expandedName)) continue;
                if (!hadAny)
                {
                    sb.AppendLine();
                    sb.AppendLine("// Expanded generic types (from _generics.h)");
                    hadAny = true;
                }
                sb.AppendLine($"typedef struct {expandedName} {expandedName};");
            }
        }

        // Typedefs + typed invokers for the generic delegate types used in source files
        // (cs2sx_delegate.h; Action without type arguments is in the runtime):
        //   Func<int, bool> → typedef CS2SX_Delegate* Func_int_int_t;
        //                     static inline int Func_int_int_Invoke(Func_int_int_t d, int a0)
        var emittedDelegateTypedefs = new HashSet<string>(StringComparer.Ordinal) { "Action_t" };
        foreach (var csFile in sourceFiles)
        {
            var source = System.IO.File.ReadAllText(csFile);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            foreach (var typeNode in tree.GetRoot()
                .DescendantNodes()
                .OfType<Microsoft.CodeAnalysis.CSharp.Syntax.GenericNameSyntax>()
                .Where(g => g.Identifier.Text is "Action" or "Func"))
            {
                var csType = typeNode.ToString().Trim();
                var isFunc = typeNode.Identifier.Text == "Func";
                var prefixLen = isFunc ? 5 : 7; // "Func<" / "Action<"
                if (!csType.EndsWith(">")) continue;

                var cName = CS2SX.Core.TypeRegistry.MapType(csType);
                if (!cName.EndsWith("_t") || !emittedDelegateTypedefs.Add(cName)) continue;

                // Each type arg becomes its mapped C type (+ * for reference types).
                var typeArgs = SplitSimpleGenericArgs(csType[prefixLen..^1].Trim())
                    .Select(a => CS2SX.Transpiler.Writers.DelegateModel.SignatureCType(a.Trim()))
                    .ToList();
                var ret = "void";
                if (isFunc)
                {
                    ret = typeArgs[^1];
                    typeArgs.RemoveAt(typeArgs.Count - 1);
                }
                sb.Append(CS2SX.Transpiler.Writers.DelegateModel.TypedefDecl(cName, typeArgs, ret));
            }
        }

        // Tuple types ((int, string) → _Tuple2_int_str) are value structs used in
        // signatures, locals and fields of any file: define each once, here.
        var tupleTypes = new SortedSet<string>(StringComparer.Ordinal);
        foreach (var f in sourceFiles)
        {
            try
            {
                var root = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(File.ReadAllText(f)).GetRoot();
                foreach (var tt in root.DescendantNodes().OfType<TupleTypeSyntax>())
                    tupleTypes.Add(tt.ToString());
            }
            catch { }
        }
        if (tupleTypes.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("// Tuple types");
            foreach (var t in tupleTypes)
                sb.Append(TypeRegistry.GenerateTupleStruct(t));
        }

        // FIX: Custom-Header aus dem Projektverzeichnis anhängen.
        // _forward.h wird von JEDEM generierten .h includiert → Custom-Funktionen
        // (z.B. Freetype_FT_Init_FreeType aus freetype_main.h) sind damit in
        // jeder Translation Unit sichtbar ohne manuelles #include.
        var customHeaders = Directory
            .GetFiles(_projectDir, "*.h")
            .Select(Path.GetFileName)
            .OrderBy(n => n)
            .ToList();

        if (customHeaders.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("// Custom project headers");
            foreach (var ch in customHeaders)
            {
                if (listUserClassTypes != null && ch != null && IsListOnlyHeader(ch, listUserClassTypes))
                {
                    Log.Warning($"Skipping '{ch}' — defines List<UserClass> types that are now auto-generated in _generics.h. Remove this file from your project.");
                    continue;
                }
                sb.AppendLine($"#include \"{ch}\"");
            }
        }

        System.IO.File.WriteAllText(outputPath, sb.ToString());
    }


    private static readonly HashSet<string> s_builtinBaseTypes = new(StringComparer.Ordinal)
    {
        "Control", "Form", "Label", "Button", "ProgressBar", "SwitchApp",
        "SwitchAppEx", "object", "Object",
    };

    /// <summary>
    /// If the source contains a class that derives from a user-defined (transpiled) base,
    /// returns "#include "BaseClass.h"\n"; otherwise returns empty string.
    /// </summary>
    /// <summary>
    /// #includes of the headers that must be complete before this file's structs: the
    /// files declaring the base class of each class here, and those declaring user
    /// structs embedded by value in fields. A forward declaration is not enough for a
    /// by-value member (`Page base;`). Types are located by declaration, not by file
    /// name — a base class may live anywhere (Page in Ui.cs).
    /// </summary>
    private static string GetUserDefinedBaseInclude(string source, IReadOnlyList<string> transpiledFiles)
    {
        try
        {
            var typeToFile = TypeToFileMap(transpiledFiles);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            var root = tree.GetRoot();
            var ownTypes = new HashSet<string>(root.DescendantNodes().OfType<BaseTypeDeclarationSyntax>()
                .Select(t => t.Identifier.Text), StringComparer.Ordinal);

            var needed = new List<string>();
            void Need(string typeName)
            {
                var name = typeName.Split('<')[0].Trim();
                if (ownTypes.Contains(name) || s_builtinBaseTypes.Contains(name)) return;
                if (typeToFile.TryGetValue(name, out var file) && !needed.Contains(file)) needed.Add(file);
            }

            foreach (var cls in root.DescendantNodes().OfType<ClassDeclarationSyntax>())
            {
                var first = cls.BaseList?.Types.FirstOrDefault()?.Type.ToString();
                if (first != null) Need(first);   // interfaces map to no file here
            }
            foreach (var field in root.DescendantNodes().OfType<FieldDeclarationSyntax>())
            {
                var t = field.Declaration.Type.ToString().Trim();
                if (s_structTypes.Contains(t)) Need(t);
            }

            return string.Concat(needed.Select(f => $"#include \"{f}.h\"\n"));
        }
        catch { return ""; }
    }

    private static Dictionary<string, string>? s_typeToFile;
    private static IReadOnlyList<string>? s_typeToFileFor;
    private static HashSet<string> s_structTypes = new(StringComparer.Ordinal);

    /// Type name → header base name (classes and structs; interfaces are in _interfaces.h).
    private static Dictionary<string, string> TypeToFileMap(IReadOnlyList<string> files)
    {
        if (s_typeToFile != null && ReferenceEquals(s_typeToFileFor, files)) return s_typeToFile;
        var map = new Dictionary<string, string>(StringComparer.Ordinal);
        var structs = new HashSet<string>(StringComparer.Ordinal);
        foreach (var f in files)
        {
            var root = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(File.ReadAllText(f)).GetRoot();
            foreach (var t in root.DescendantNodes().OfType<TypeDeclarationSyntax>()
                         .Where(t => t is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax))
            {
                map.TryAdd(t.Identifier.Text, Path.GetFileNameWithoutExtension(f));
                if (t is StructDeclarationSyntax
                    || t is RecordDeclarationSyntax r && r.ClassOrStructKeyword.Text == "struct")
                    structs.Add(t.Identifier.Text);
            }
        }
        s_typeToFile = map;
        s_typeToFileFor = files;
        s_structTypes = structs;
        return map;
    }

    private static List<string> SplitSimpleGenericArgs(string s)
    {
        var result = new List<string>();
        int depth = 0, start = 0;
        for (int i = 0; i < s.Length; i++)
        {
            if (s[i] == '<') depth++;
            else if (s[i] == '>') depth--;
            else if (s[i] == ',' && depth == 0)
            {
                result.Add(s.Substring(start, i - start));
                start = i + 1;
            }
        }
        if (start < s.Length) result.Add(s.Substring(start));
        return result;
    }

    private static string WrapHeader(string baseName, string content)
