using CS2SX.Core;
using CS2SX.Logging;
using CS2SX.Transpiler;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using System.Text;

namespace CS2SX.Build;

public sealed class BuildPipeline
{
    private readonly ProjectConfig _config;
    private readonly string _projectDir;
    private readonly string _buildDir;

    // Headers generated by the build pipeline itself (not transpiled from user code).
    // Add new generated headers here when introducing new pipeline stages; IsUpToDate()
    // uses this list to trigger a full rebuild when any of these change.
    internal static readonly string[] GeneratedHeaders =
    {
        "_forward.h", "_generics.h", "_interfaces.h",
        "switchforms.h", "switchapp.h", "AudioStub.h", "FtpStub.h", "NetStub.h", "cs2sx_prelude.h", "cs2sx_gfx.h", "cs2sx_gfx_shaders.h", "cs2sx_exc.h", "cs2sx_delegate.h",
    };

    private readonly bool _transpileOnly;

    public BuildPipeline(string csprojPath, bool transpileOnly = false)
    {
        _transpileOnly = transpileOnly;
        _projectDir = Path.GetDirectoryName(Path.GetFullPath(csprojPath))
            ?? throw new ArgumentException("Ungültiger Pfad", nameof(csprojPath));
        _config = ProjectConfig.Load(_projectDir);
        _buildDir = Path.Combine(_projectDir, "cs2sx_out");
    }

    public void Clean()
    {
        if (!Directory.Exists(_buildDir))
        {
            Log.Info("cs2sx_out does not exist — nothing to clean.");
            return;
        }

        int deleted = 0;
        foreach (var f in Directory.GetFiles(_buildDir))
        {
            try { File.Delete(f); deleted++; }
            catch (Exception ex) { Log.Warning($"Could not delete {Path.GetFileName(f)}: {ex.Message}"); }
        }
        Log.Ok($"Cleaned cs2sx_out: {deleted} file(s) removed.");
    }

    public void Run()
    {
        var started = DateTime.Now;

        using var renderer = new BuildRenderer([
            new BuildStage { Name = "prepare"   },
            new BuildStage { Name = "fwd-decl"  },
            new BuildStage { Name = "generics"  },
            new BuildStage { Name = "semantic"  },
            new BuildStage { Name = "transpile" },
            new BuildStage { Name = "compile"   },
            new BuildStage { Name = "package"   },
        ]);
        Log.AttachRenderer(renderer);

        int warnings = 0;
        string? apiSourceDir = null;

        try
        {
            // ── prepare ───────────────────────────────────────────────────
            var sPrepare = renderer.GetStage("prepare");
            sPrepare.Status = StageStatus.Running;

            Directory.CreateDirectory(_buildDir);
            CleanOrphanedFiles(_buildDir);

            var csprojFiles = Directory.GetFiles(_projectDir, "*.csproj");
            if (csprojFiles.Length == 0)
                throw new FileNotFoundException("Keine .csproj-Datei gefunden in: " + _projectDir);

            Log.Info($"{_config.Name} v{_config.Version} by {_config.Author}");

            var reader = new ProjectReader();
            reader.Load(csprojFiles[0]);

            if (reader.SourceFiles.Count == 0)
                throw new InvalidOperationException("Keine .cs-Quelldateien gefunden.");

            Log.Info($"{reader.SourceFiles.Count} source file(s) found");
            var runtimeSources = RuntimeExporter.Export(_buildDir);

            var switchformsCPath = Path.Combine(_buildDir, "switchforms.c");
            // RomFS is only mounted when the build embeds one (romfs/ exists).
            WriteSwitchformsC(switchformsCPath, hasRomfs: Directory.Exists(Path.Combine(_projectDir, "romfs")));

            sPrepare.Progress = 100;
            sPrepare.Status = StageStatus.Done;
            sPrepare.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            // ── fwd-decl ──────────────────────────────────────────────────
            var sFwd = renderer.GetStage("fwd-decl");
            sFwd.Status = StageStatus.Running;

            apiSourceDir = RuntimeExporter.ExportApiSourcesToTemp();

            var apiSourceFiles = Directory.GetFiles(apiSourceDir, "*.cs").ToList();
            // Generic methods are specialised per type at the C# level first; every later
            // stage (forward declarations, generics, transpiling) sees the result.
            var appSourceFiles = GenericMethodMonomorphizer.Rewrite(reader.SourceFiles.ToList(), _buildDir);
            var allForFwd = apiSourceFiles.Concat(appSourceFiles).ToList();
            var forwardPath = Path.Combine(_buildDir, "_forward.h");
            WriteForwardDeclarations(allForFwd, forwardPath, expandedTypeNames: null);

            sFwd.Progress = 100;
            sFwd.Status = StageStatus.Done;
            sFwd.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            // ── generics ──────────────────────────────────────────────────
            var sGenerics = renderer.GetStage("generics");
            sGenerics.Status = StageStatus.Running;
            sGenerics.Detail = "collecting instantiations…";

            var transpiledFiles = appSourceFiles.ToList();

            // Project-wide type facts (user enums/structs, operator overloads) must be
            // known before generics expansion and before any file is transpiled.
            CS2SX.Transpiler.Writers.OperatorOverloadWriter.Reset();
            ProjectTypeScanner.RegisterUserTypes(transpiledFiles);

            var genericCollector = new GenericInstantiationCollector();
            genericCollector.Collect(transpiledFiles, apiSourceFiles);

            var interfaceExpander = new InterfaceExpander(genericCollector);
            interfaceExpander.AnalyzeImplementations(transpiledFiles);

            var ifaceHeaderPath = interfaceExpander.WriteInterfaceHeader(_buildDir);

            var genericExpander = new GenericExpander(genericCollector);
            var (genericHeaderPath, genericImplPath) = genericExpander.WriteToFiles(_buildDir, transpiledFiles);

            var expandedNames = genericExpander.GetExpandedTypeNames().ToList();
            var listUserClasses = genericCollector.ListOfUserClassInstantiations;
            if (expandedNames.Count > 0 || listUserClasses.Count > 0)
            {
                WriteForwardDeclarations(allForFwd, forwardPath, expandedNames, listUserClasses);
                Log.Info($"_forward.h aktualisiert mit {expandedNames.Count} expanded type(s)");
            }

            var genericsInfo = new List<string>();
            if (genericCollector.GenericClasses.Count > 0)
                genericsInfo.Add($"{genericCollector.GenericClasses.Count} generic class(es)");
            if (genericCollector.Interfaces.Count > 0)
                genericsInfo.Add($"{genericCollector.Interfaces.Count} interface(s)");
            if (genericCollector.ExtensionMethods.Count > 0)
                genericsInfo.Add($"{genericCollector.ExtensionMethods.Values.SelectMany(v => v).Count()} extension method(s)");
            if (genericCollector.Instantiations.Count > 0)
                genericsInfo.Add($"{genericCollector.Instantiations.Count} instantiation(s)");
            if (genericCollector.ListOfUserClassInstantiations.Count > 0)
                genericsInfo.Add($"{genericCollector.ListOfUserClassInstantiations.Count} List<UserClass>(es)");

            sGenerics.Detail = genericsInfo.Count > 0
                ? string.Join(", ", genericsInfo)
                : "nothing to expand";
            sGenerics.Progress = 100;
            sGenerics.Status = StageStatus.Done;
            sGenerics.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            // ── semantic ──────────────────────────────────────────────────
            var sSemantic = renderer.GetStage("semantic");
            sSemantic.Status = StageStatus.Running;
            sSemantic.Detail = "building Roslyn compilation…";

            var semanticBuilder = new SemanticModelBuilder(transpiledFiles);

            Log.Info($"SemanticModel: {transpiledFiles.Count} file(s) analysed");

            sSemantic.Progress = 100;
            sSemantic.Status = StageStatus.Done;
            sSemantic.Detail = $"{transpiledFiles.Count} file(s)";
            sSemantic.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            // ── transpile (incremental) ───────────────────────────────────
            var sTranspile = renderer.GetStage("transpile");
            sTranspile.Status = StageStatus.Running;

            // Shared diagnostic reporter collects source maps from ALL transpiled files.
            // Passed to CCompiler so GCC errors can be mapped back to C# line numbers.
            var sharedDiagnostics = new DiagnosticReporter();

            var allHeaders = transpiledFiles
                .Select(f => Path.GetFileNameWithoutExtension(f) + ".h")
                .ToList();

            // _generics.h must come before _interfaces.h — interfaces use List_T types defined in generics.
            // Insert _interfaces.h first (→ pos 0), then _generics.h (→ pos 0, pushing iface to pos 1).
            if (!string.IsNullOrEmpty(ifaceHeaderPath))
                allHeaders.Insert(0, Path.GetFileName(ifaceHeaderPath));
            if (!string.IsNullOrEmpty(genericHeaderPath))
                allHeaders.Insert(0, Path.GetFileName(genericHeaderPath));

            var cFiles = new List<string> { switchformsCPath };
            cFiles.AddRange(runtimeSources);   // runtime modules — compiled once, then cached

            if (!string.IsNullOrEmpty(genericImplPath) && File.Exists(genericImplPath))
            {
                // Expanded generic classes call functions of the user's classes
                // (Box<Node> releases its Node): include every header like any C file.
                var impl = File.ReadAllText(genericImplPath);
                impl = impl.Replace("#include \"_generics.h\"\n",
                    string.Concat(allHeaders.Select(h => $"#include \"{h}\"\n")));
                File.WriteAllText(genericImplPath, impl);
                cFiles.Add(genericImplPath);
            }

            int transpiled = 0;
            int skipped = 0;
            int transpileErrors = 0;

            var allTranspiledHeaders = transpiledFiles
                .Select(f => Path.Combine(_buildDir, Path.GetFileNameWithoutExtension(f) + ".h"))
                .Where(File.Exists)
                .ToList();

            var generatedHeaders = new[] { "_generics.h", "_interfaces.h", "_forward.h" }
                .Select(n => Path.Combine(_buildDir, n))
                .Where(File.Exists);
            allTranspiledHeaders.AddRange(generatedHeaders);

            // FIX: Custom-Header aus dem Projektverzeichnis in die Timestamp-Berechnung einbeziehen.
            // Vorher wurden diese erst NACH dem Transpile-Loop zu allHeaders hinzugefügt und
            // beeinflussten latestHeaderTime nicht → Änderungen an Custom-Headern triggerten
            // keine Neu-Transpilierung.
            var customProjectHeaders = Directory.GetFiles(_projectDir, "*.h")
                .Where(h => File.Exists(h))
                .ToList();
            allTranspiledHeaders.AddRange(customProjectHeaders);

            var latestHeaderTime = allTranspiledHeaders.Count > 0
                ? allTranspiledHeaders.Max(h => File.GetLastWriteTimeUtc(h))
                : DateTime.MinValue;

            // Pre-scan all source files for VTable types so cross-file virtual dispatch
            // works (e.g. Window.cs calling UIControl.Draw which is defined in UIControl.cs).
            var sharedVTableTypes = PreScanVTableTypes(transpiledFiles);

            // Pre-scan for overloaded methods so cross-file call sites get the correct
            // suffixed C name (e.g. Desktop.cs calling Window.Draw(dimmed) → Window_Draw_1).
            var sharedOverloadedMethods = PreScanOverloadedMethods(transpiledFiles);

            // Pre-scan virtual-method slots so only virtual calls route through vtables.
            var sharedVTableMethods = PreScanVTableMethods(transpiledFiles);

            // Pre-scan multi-level inheritance (vtable-root type + hops to root).
            var (sharedVTableRoot, sharedRootHops) = PreScanInheritance(transpiledFiles);

            // Pre-scan class member types so the inferrer can type obj.Member.
            var sharedClassMemberTypes = PreScanClassMemberTypes(transpiledFiles);


            for (int i = 0; i < transpiledFiles.Count; i++)
            {
                var csFile = transpiledFiles[i];
                var baseName = Path.GetFileNameWithoutExtension(csFile);
                sTranspile.Detail = $"{baseName}.cs";
                sTranspile.Progress = (int)((i + 1) / (double)transpiledFiles.Count * 100);

                var hPath = Path.Combine(_buildDir, baseName + ".h");
                var cPath = Path.Combine(_buildDir, baseName + ".c");

                if (IsUpToDate(csFile, hPath, cPath, latestHeaderTime))
                {
                    Log.Info($"→ {baseName}.cs (unchanged)");
                    cFiles.Add(cPath);
                    skipped++;
                    continue;
                }

                Log.Info($"→ {baseName}.cs");

                var source = System.IO.File.ReadAllText(csFile);
                var semanticModel = semanticBuilder.GetModel(csFile);

                // ── Header transpilieren ──────────────────────────────────

                var hTranspiler = new CSharpToC(
                    CSharpToC.TranspileMode.HeaderOnly,
                    genericCollector,
                    interfaceExpander,
                    sharedDiagnostics);

                hTranspiler.GetContext().CurrentFile = Path.GetFileName(csFile);
                hTranspiler.GetContext().CurrentCFile = baseName + ".h";
                foreach (var vt in sharedVTableTypes)
                    hTranspiler.GetContext().VTableTypes.Add(vt);
                foreach (var (cls, set) in sharedOverloadedMethods)
                    hTranspiler.GetContext().OverloadedMethods[cls] = set;
                foreach (var (cls, set) in sharedVTableMethods)
                    hTranspiler.GetContext().VTableMethods[cls] = set;
                foreach (var (cls, r) in sharedVTableRoot)
                    hTranspiler.GetContext().VTableRoot[cls] = r;
                foreach (var (cls, h) in sharedRootHops)
                    hTranspiler.GetContext().RootHops[cls] = h;
                foreach (var (cls, m) in sharedClassMemberTypes)
                    hTranspiler.GetContext().ClassMemberTypes[cls] = m;

                var hResult = hTranspiler.Transpile(source, csFile, semanticModel);

                var interfaceInclude = !string.IsNullOrEmpty(ifaceHeaderPath)
                    ? $"#include \"{Path.GetFileName(ifaceHeaderPath)}\"\n"
                    : "";
                var genericInclude = !string.IsNullOrEmpty(genericHeaderPath)
                    ? $"#include \"{Path.GetFileName(genericHeaderPath)}\"\n"
                    : "";

                // If this class derives from a user-defined base, include its header so
                // embedded struct fields compile (forward-decl alone is not enough).
                var baseClassInclude = GetUserDefinedBaseInclude(source, transpiledFiles);

                var hContent = WrapHeader(baseName,
                    "#include \"_forward.h\"\n"
                    + baseClassInclude
                    + interfaceInclude
                    + genericInclude
                    + "\n" + hResult.Code);
                System.IO.File.WriteAllText(hPath, hContent);

                // ── Implementation transpilieren ──────────────────────────

                var allIncludes = string.Join("\n",
                    allHeaders.Select(h => $"#include \"{h}\""));

                var cTranspiler = new CSharpToC(
                    CSharpToC.TranspileMode.Implementation,
                    genericCollector,
                    interfaceExpander,
                    sharedDiagnostics);

                cTranspiler.GetContext().CurrentFile = Path.GetFileName(csFile);
                cTranspiler.GetContext().CurrentCFile = baseName + ".c";
                foreach (var vt in sharedVTableTypes)
                    cTranspiler.GetContext().VTableTypes.Add(vt);
                foreach (var (cls, set) in sharedOverloadedMethods)
                    cTranspiler.GetContext().OverloadedMethods[cls] = set;
                foreach (var (cls, set) in sharedVTableMethods)
                    cTranspiler.GetContext().VTableMethods[cls] = set;
                foreach (var (cls, r) in sharedVTableRoot)
                    cTranspiler.GetContext().VTableRoot[cls] = r;
                foreach (var (cls, h) in sharedRootHops)
                    cTranspiler.GetContext().RootHops[cls] = h;
                foreach (var (cls, m) in sharedClassMemberTypes)
                    cTranspiler.GetContext().ClassMemberTypes[cls] = m;

                var cResult = cTranspiler.Transpile(source, csFile, semanticModel);

                var cContent = "#include <stdlib.h>\n"
                             + allIncludes + "\n\n"
                             + cResult.Code;
                System.IO.File.WriteAllText(cPath, cContent);

                // ── Diagnostics ausgeben ──────────────────────────────────

                var allDiags = hResult.Diagnostics
                    .Concat(cResult.Diagnostics)
                    .DistinctBy(d => (d.CsFile, d.CsLine, d.Message))
                    .OrderBy(d => d.CsLine)
                    .ToList();

                // A line with an error needs no further "check generated C" warnings.
                var errorLines = allDiags.Where(d => d.Severity == DiagnosticSeverity.Error)
                    .Select(d => d.CsLine).ToHashSet();
                foreach (var d in allDiags.Where(d => d.Severity == DiagnosticSeverity.Warning
                                                      && !errorLines.Contains(d.CsLine)))
                    Log.Warning($"{Path.GetFileName(d.CsFile ?? "")}({d.CsLine}): {d.Message}"
                        + (d.Context != null ? $"\n  code: {d.Context}" : ""));

                foreach (var d in allDiags.Where(d => d.Severity == DiagnosticSeverity.Error))
                    Log.Error($"{Path.GetFileName(d.CsFile ?? "")}({d.CsLine}): {d.Message}");

                foreach (var d in allDiags.Where(d => d.Message.Contains("UNSUPPORTED") || d.Message.Contains("unknown call")))
                    Log.Warning($"  ↳ unsupported construct in {Path.GetFileName(csFile)} — check generated C");

                warnings += allDiags.Count(d => d.Severity == DiagnosticSeverity.Warning);

                var fileErrors = allDiags.Count(d => d.Severity == DiagnosticSeverity.Error);
                if (fileErrors > 0)
                {
                    // Not a usable translation: drop it so the next build transpiles the
                    // file again (unchanged files are skipped) and reports the errors.
                    transpileErrors += fileErrors;
                    File.Delete(cPath);
                    File.Delete(hPath);
                }

                cFiles.Add(cPath);
                transpiled++;
            }

            if (transpileErrors > 0)
                throw new CSharpErrorsException(transpileErrors);

            sTranspile.Detail = transpiled > 0
                ? $"{transpiled} transpiled, {skipped} unchanged"
                : $"all {skipped} unchanged";

            sTranspile.Progress = 100;
            sTranspile.Status = StageStatus.Done;
            sTranspile.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            if (_transpileOnly)
            {
                Log.Ok($"→ {_buildDir} (transpile only)");
                renderer.Complete(DateTime.Now - started, warnings, errors: 0);
                return;
            }

            // ── compile ───────────────────────────────────────────────────
            var sCompile = renderer.GetStage("compile");
            sCompile.Status = StageStatus.Running;

            var appClass = FindSwitchAppClass(appSourceFiles) ?? _config.MainClass;
            var appHeaderFile = FindHeaderForClass(appSourceFiles, appClass)
                              ?? (appClass + ".h");
            var mainPath = EntryPointGenerator.Write(
                _buildDir, appClass, appHeaderFile, allHeaders);
            cFiles.Add(mainPath);

            foreach (var hFile in Directory.GetFiles(_projectDir, "*.h"))
            {
                var fileName = Path.GetFileName(hFile);
                if (fileName == null) continue;
                if (IsListOnlyHeader(fileName, listUserClasses))
                {
                    Log.Warning($"Skipping '{fileName}' — defines List<UserClass> types that are now auto-generated. Remove this file from your project.");
                    continue;
                }
                var dest = Path.Combine(_buildDir, fileName);
                System.IO.File.Copy(hFile, dest, overwrite: true);
                Log.Info($"Custom header: {fileName}");

                // FIX: Custom-Header am Ende von allHeaders eintragen
                // → wird in jede .c-Datei als #include eingezogen
                // Reihenfolge: erst die transpilierten Header, dann die Custom-Header
                // (damit Custom-Header auf die Transpiler-Typen zugreifen können)
                if (fileName != null && !allHeaders.Contains(fileName))
                    allHeaders.Add(fileName);
            }

            sCompile.Detail = $"{cFiles.Count} translation unit(s)";
            var elfPath = Path.Combine(_buildDir, _config.Name + ".elf");


            // ExternLibs aus Config laden — FIX: ExtraIncludeDirs + Defines weitergeben
            var externLibs = _config.ExternLibs
                .Select(lib => new CCompiler.ExternLib(
                    lib.Name,
                    lib.Sources
                        .Select(s => Path.GetFullPath(Path.Combine(_projectDir, s)))
                        .Where(File.Exists)
                        .ToList(),
                    lib.IncludeDir != null
                        ? Path.GetFullPath(Path.Combine(_projectDir, lib.IncludeDir))
                        : null,
                    lib.ExtraIncludeDirs
                        .Select(d => Path.GetFullPath(Path.Combine(_projectDir, d)))
                        .Where(Directory.Exists)
                        .ToList(),
                    lib.Defines.ToList()))
                .Where(lib => lib.Sources.Count > 0)
                .ToList();

            if (externLibs.Count > 0)
                Log.Info($"ExternLibs: {string.Join(", ", externLibs.Select(l => l.Name))}");

            // Optional runtime modules (fonts → FreeType) only when the app uses them.
            var optionalLibs = OptionalRuntimeModules.Select(cFiles);
            if (optionalLibs.Count > 0)
                Log.Info($"Optional runtime libs: {string.Join(", ", optionalLibs)}");

            var compiler = new CCompiler();
            compiler.Compile(cFiles, elfPath, _buildDir, _projectDir,
                diagnostics: sharedDiagnostics,
                externLibs: externLibs,
                linkLibs: optionalLibs);
            sCompile.Detail = $"{compiler.CompiledCount} compiled, {compiler.CachedCount} cached";

            sCompile.Progress = 100;
            sCompile.Status = StageStatus.Done;
            sCompile.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            // ── package ───────────────────────────────────────────────────
            var sPackage = renderer.GetStage("package");
            sPackage.Status = StageStatus.Running;
            sPackage.Detail = "nacp + nro";

            var nacpPath = Path.Combine(_buildDir, _config.Name + ".nacp");
            new NacpBuilder().Build(nacpPath, _config.Name, _config.Author, _config.Version);
            sPackage.Progress = 50;

            var nroPath = Path.Combine(_projectDir, _config.Name + ".nro");
            var iconPath = _config.Icon != null
                ? Path.Combine(_projectDir, _config.Icon)
                : TryFindDefaultIcon(_projectDir);

            if (iconPath == null)
            {
                Log.Warning("No icon found — using default");
                warnings++;
            }

            var romfsDir = Path.Combine(_projectDir, "romfs");
            if (!Directory.Exists(romfsDir)) romfsDir = null;
            if (romfsDir != null) Log.Info($"romfs: {romfsDir}");

            new NroBuilder().Build(elfPath, nroPath, nacpPath, iconPath, romfsDir);

            sPackage.Progress = 100;
            sPackage.Status = StageStatus.Done;
            sPackage.Detail = nroPath;
            sPackage.Elapsed = $"{(DateTime.Now - started).TotalMilliseconds:F0}ms";

            Log.Ok($"→ {nroPath}");
            renderer.Complete(DateTime.Now - started, warnings, errors: 0);
        }
        catch (Exception ex)
        {
            Log.Error(ex.Message);

            // FIX-1: Kein hartcodiertes String-Array mehr.
            // Der Renderer findet den fehlgeschlagenen Stage selbst.
            renderer.MarkFirstRunningAsFailed();
            renderer.Complete(DateTime.Now - started, warnings,
                errors: ex is CSharpErrorsException ce ? ce.Count : 1);
            throw;
        }
        finally
        {
            Log.DetachRenderer();

            if (apiSourceDir != null && Directory.Exists(apiSourceDir))
            {
                try { Directory.Delete(apiSourceDir, recursive: true); }
                catch { /* Nicht kritisch — Temp-Verzeichnis, OS räumt auf */ }
            }
        }
    }

    // ── Orphaned-File-Cleanup ─────────────────────────────────────────────────

    private void CleanOrphanedFiles(string buildDir)
    {
        var reader = new ProjectReader();
        var csprojFiles = Directory.GetFiles(_projectDir, "*.csproj");
        if (csprojFiles.Length == 0) return;
        reader.Load(csprojFiles[0]);

        var validBases = new HashSet<string>(
            reader.SourceFiles.Select(f => Path.GetFileNameWithoutExtension(f)),
            StringComparer.OrdinalIgnoreCase);

        foreach (var h in GeneratedHeaders)
            validBases.Add(Path.GetFileNameWithoutExtension(h));
        validBases.Add("switchforms");
        validBases.Add("main");
        validBases.Add("switchapp");
        validBases.Add("switchforms_globals");

        // FIX: Custom-Header aus dem Projektverzeichnis nicht löschen.
        // freetype_main.h, freetype_shim.h etc. werden von BuildPipeline
        // in cs2sx_out/ kopiert — CleanOrphanedFiles darf sie nicht entfernen.
        var customHeaderBases = Directory
            .GetFiles(_projectDir, "*.h")
            .Select(f => Path.GetFileNameWithoutExtension(f));
        foreach (var ch in customHeaderBases)
            validBases.Add(ch);

        int removed = 0;
        foreach (var file in Directory.GetFiles(buildDir, "*.c")
            .Concat(Directory.GetFiles(buildDir, "*.h")))
        {
            var baseName = Path.GetFileNameWithoutExtension(file);
            if (!validBases.Contains(baseName))
            {
                try { File.Delete(file); removed++; Log.Info($"Orphan removed: {Path.GetFileName(file)}"); }
                catch { }
            }
        }
        if (removed > 0)
            Log.Info($"Cleaned {removed} orphaned file(s) from cs2sx_out");
    }

    private bool IsUpToDate(string csFile, string hPath, string cPath,
    DateTime latestHeaderTime = default)
    {
        if (!File.Exists(hPath) || !File.Exists(cPath)) return false;

        var csTime = File.GetLastWriteTimeUtc(csFile);
        var hTime = File.GetLastWriteTimeUtc(hPath);
        var cTime = File.GetLastWriteTimeUtc(cPath);

        // Source file newer than either output → rebuild
        if (hTime < csTime || cTime < csTime) return false;

        // Transpiler binary newer → rebuild all
        var transpilerPath = System.Reflection.Assembly.GetExecutingAssembly().Location;
        if (!string.IsNullOrEmpty(transpilerPath) && File.Exists(transpilerPath))
        {
            var transpilerTime = File.GetLastWriteTimeUtc(transpilerPath);
            if (transpilerTime > hTime || transpilerTime > cTime)
                return false;
        }

        // Check every generated header individually (not just the latest)
        // This ensures that a change to _generics.h triggers recompile of every
        // dependent .c file, even when other headers are unchanged.
        var generatedHeaderNames = GeneratedHeaders;

        foreach (var headerName in generatedHeaderNames)
        {
            var headerPath = Path.Combine(_buildDir, headerName);
            if (!File.Exists(headerPath)) return false;
            var ht = File.GetLastWriteTimeUtc(headerPath);
            if (ht > hTime || ht > cTime) return false;
        }

        // Any transpiled header newer than this file's output → rebuild
        // (a struct definition change in AnyOther.h may affect this .c)
        if (latestHeaderTime != default && (latestHeaderTime > hTime || latestHeaderTime > cTime))
            return false;

        return true;
    }

    /// <summary>
    /// Scans all source files for classes with virtual/abstract methods and returns
    /// a set of those type names plus their subclass names.
    /// Used to pre-populate VTableTypes in each per-file TranspilerContext so that
    /// cross-file virtual dispatch (e.g. UIControl.Draw called from Window.cs) works.
    /// </summary>
    internal static HashSet<string> PreScanVTableTypes(IEnumerable<string> sourceFiles)
    {
        var result = new HashSet<string>(StringComparer.Ordinal);
        var classToBase = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var file in sourceFiles)
        {
            try
            {
                var src = File.ReadAllText(file);
                var tree = CSharpSyntaxTree.ParseText(src,
                    new CSharpParseOptions(LanguageVersion.CSharp12));
                foreach (var cls in tree.GetRoot().DescendantNodes()
                    .OfType<ClassDeclarationSyntax>())
                {
                    if (VTableBuilder.HasVirtualMethods(cls))
                        result.Add(cls.Identifier.Text);

                    var baseTypeName = cls.BaseList?.Types.FirstOrDefault()?.Type.ToString().Trim();
                    if (!string.IsNullOrEmpty(baseTypeName))
                        classToBase[cls.Identifier.Text] = baseTypeName;
                }
            }
            catch { }
        }

        // Propagate: if a class inherits from a VTable type, it's also a VTable type
        bool changed = true;
        while (changed)
        {
            changed = false;
            foreach (var (cls, baseType) in classToBase)
            {
                if (!result.Contains(cls) && result.Contains(baseType))
                {
                    result.Add(cls);
                    changed = true;
                }
            }
        }

        return result;
    }

    /// <summary>
    /// For each class, the set of method names that are actual virtual slots
    /// (own virtual/abstract/override + inherited). Lets call sites route ONLY
    /// virtual methods through the vtable; non-virtual methods on the same class
    /// use a direct call instead of a nonexistent vtable member.
    /// </summary>
    internal static Dictionary<string, HashSet<string>> PreScanVTableMethods(
        IEnumerable<string> sourceFiles)
    {
        var own = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        var classToBase = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var file in sourceFiles)
        {
            try
            {
                var src = File.ReadAllText(file);
                var tree = CSharpSyntaxTree.ParseText(src,
                    new CSharpParseOptions(LanguageVersion.CSharp12));
                foreach (var cls in tree.GetRoot().DescendantNodes()
                    .OfType<ClassDeclarationSyntax>())
                {
                    var set = own.TryGetValue(cls.Identifier.Text, out var ex)
                        ? ex : new HashSet<string>(StringComparer.Ordinal);
                    foreach (var m in cls.Members.OfType<MethodDeclarationSyntax>())
                        if (m.Modifiers.Any(mod =>
                            mod.ValueText is "virtual" or "abstract" or "override"))
                            set.Add(m.Identifier.Text);
                    own[cls.Identifier.Text] = set;

                    var baseTypeName = cls.BaseList?.Types.FirstOrDefault()?.Type.ToString().Trim();
                    if (!string.IsNullOrEmpty(baseTypeName))
                        classToBase[cls.Identifier.Text] = baseTypeName!;
                }
            }
            catch { }
        }

        // Merge inherited slots from the base chain into each class.
        var result2 = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var cls in own.Keys)
        {
            var merged = new HashSet<string>(own[cls], StringComparer.Ordinal);
            var cur = cls;
            int guard = 0;
            while (classToBase.TryGetValue(cur, out var b) && guard++ < 32)
            {
                if (own.TryGetValue(b, out var bset)) merged.UnionWith(bset);
                cur = b;
            }
            result2[cls] = merged;
        }
        return result2;
    }

    /// <summary>
    /// Per-class map of member (field/property/auto-property) name → C# type, with
    /// inherited members merged in. Used by the type inferrer to resolve `obj.Member`
    /// types when the semantic model can't (e.g. LINQ-lambda parameters).
    /// </summary>
    internal static Dictionary<string, Dictionary<string, string>>
        PreScanClassMemberTypes(IEnumerable<string> sourceFiles)
    {
        var own    = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        var baseOf = new Dictionary<string, string>(StringComparer.Ordinal);

        foreach (var file in sourceFiles)
        {
            try
            {
                var src = File.ReadAllText(file);
                var tree = CSharpSyntaxTree.ParseText(src,
                    new CSharpParseOptions(LanguageVersion.CSharp12));
                foreach (var cls in tree.GetRoot().DescendantNodes()
                    .OfType<TypeDeclarationSyntax>()
                    .Where(t => t is ClassDeclarationSyntax or StructDeclarationSyntax or RecordDeclarationSyntax))
                {
                    var map = own.TryGetValue(cls.Identifier.Text, out var ex)
                        ? ex : new Dictionary<string, string>(StringComparer.Ordinal);
                    if (cls.ParameterList != null) // positional record / primary ctor
                        foreach (var rp in cls.ParameterList.Parameters)
                            if (rp.Type != null) map[rp.Identifier.Text] = rp.Type.ToString().Trim();
                    foreach (var f in cls.Members.OfType<FieldDeclarationSyntax>())
                    {
                        var ft = f.Declaration.Type.ToString().Trim();
                        foreach (var dv in f.Declaration.Variables)
                            map[dv.Identifier.Text] = ft;
                    }
                    foreach (var p in cls.Members.OfType<PropertyDeclarationSyntax>())
                        map[p.Identifier.Text] = p.Type.ToString().Trim();
                    own[cls.Identifier.Text] = map;

                    var b = cls.BaseList?.Types.FirstOrDefault()?.Type.ToString().Trim();
                    if (!string.IsNullOrEmpty(b)) baseOf[cls.Identifier.Text] = b!;
                }
            }
            catch { }
        }

        // Merge inherited members down the chain.
        var result = new Dictionary<string, Dictionary<string, string>>(StringComparer.Ordinal);
        foreach (var cls in own.Keys)
        {
            var merged = new Dictionary<string, string>(own[cls], StringComparer.Ordinal);
            var cur = cls; int guard = 0;
            while (baseOf.TryGetValue(cur, out var b) && guard++ < 32)
            {
                if (own.TryGetValue(b, out var bmap))
                    foreach (var kv in bmap) merged.TryAdd(kv.Key, kv.Value);
                cur = b;
            }
            result[cls] = merged;
        }
        return result;
    }

    /// <summary>
    /// For multi-level user inheritance: computes, per class, (a) the ancestor that
    /// declares the vtable struct (the `_vtable` type name to use), and (b) how many
    /// `base.` hops reach the absolute user root (where _rc / vtable physically live).
    /// </summary>
    internal static (Dictionary<string, string> VTableRoot, Dictionary<string, int> RootHops)
        PreScanInheritance(IEnumerable<string> sourceFiles)
    {
        var baseOf    = new Dictionary<string, string>(StringComparer.Ordinal);
        var hasVirt   = new Dictionary<string, bool>(StringComparer.Ordinal);
        var userClasses = new HashSet<string>(StringComparer.Ordinal);

        foreach (var file in sourceFiles)
        {
            try
            {
                var src = File.ReadAllText(file);
                var tree = CSharpSyntaxTree.ParseText(src,
                    new CSharpParseOptions(LanguageVersion.CSharp12));
                foreach (var cls in tree.GetRoot().DescendantNodes()
                    .OfType<ClassDeclarationSyntax>())
                {
                    userClasses.Add(cls.Identifier.Text);
                    hasVirt[cls.Identifier.Text] = VTableBuilder.HasVirtualMethods(cls);
                    var b = cls.BaseList?.Types.FirstOrDefault()?.Type.ToString().Trim();
                    if (!string.IsNullOrEmpty(b)) baseOf[cls.Identifier.Text] = b!;
                }
            }
            catch { }
        }

        var vtableRoot = new Dictionary<string, string>(StringComparer.Ordinal);
        var rootHops   = new Dictionary<string, int>(StringComparer.Ordinal);

        foreach (var cls in userClasses)
        {
            // Walk up the chain of USER bases only (stop at runtime/SwitchApp bases).
            int hops = 0;
            string cur = cls;
            string? topVirt = hasVirt.TryGetValue(cls, out var hv0) && hv0 ? cls : null;
            int guard = 0;
            while (baseOf.TryGetValue(cur, out var b)
                   && userClasses.Contains(b) && guard++ < 32)
            {
                hops++;
                if (hasVirt.TryGetValue(b, out var hvb) && hvb) topVirt = b;
                cur = b;
            }
            // A user root deriving from a System exception: _rc lives one level deeper,
            // in the runtime's Exception struct (self->base[.base…]._rc).
            if (baseOf.TryGetValue(cur, out var rootBase) && TypeRegistry.IsBuiltinException(rootBase))
                hops++;
            rootHops[cls] = hops;
            if (topVirt != null) vtableRoot[cls] = topVirt;
        }
        return (vtableRoot, rootHops);
    }

    /// <summary>
    /// Scans all source files for classes with overloaded methods (same name, different param count).
    /// Returns a map of class name → set of overloaded method names.
    /// Shared across all per-file TranspilerContexts so that cross-file call sites can
    /// generate the correct suffixed C name (e.g. Window_Draw_1 vs Window_Draw_0).
    /// </summary>
    internal static Dictionary<string, HashSet<string>> PreScanOverloadedMethods(IEnumerable<string> sourceFiles)
    {
        var result = new Dictionary<string, HashSet<string>>(StringComparer.Ordinal);
        foreach (var file in sourceFiles)
        {
            try
            {
                var src = File.ReadAllText(file);
                var tree = CSharpSyntaxTree.ParseText(src,
                    new CSharpParseOptions(LanguageVersion.CSharp12));
                foreach (var cls in tree.GetRoot().DescendantNodes()
                    .OfType<TypeDeclarationSyntax>())
                {
                    var className = cls.Identifier.Text;
                    var set = new HashSet<string>(StringComparer.Ordinal);
                    foreach (var g in cls.Members.OfType<MethodDeclarationSyntax>()
                                 .GroupBy(m => m.Identifier.Text)
                                 .Where(g => g.Count() > 1))
                        set.Add(g.Key);
                    if (set.Count > 0)
                        result[className] = set;
                }
            }
            catch { }
        }
        return result;
    }

