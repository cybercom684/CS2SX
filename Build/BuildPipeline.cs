    }

    // FIX: "static" entfernt → Zugriff auf _projectDir möglich
    private void WriteForwardDeclarations(
        IReadOnlyList<string> sourceFiles,
        string outputPath,
        IEnumerable<string>? expandedTypeNames = null,
        IReadOnlySet<string>? listUserClassTypes = null)
    {
        var sb = new StringBuilder();
        sb.AppendLine("#pragma once");
        sb.AppendLine("#include <setjmp.h>");
        sb.AppendLine("#include <switch.h>");
        sb.AppendLine("#include <stdlib.h>");
        sb.AppendLine("#include <string.h>");
        sb.AppendLine("#include <stdio.h>");
        sb.AppendLine("#include <stdbool.h>");
        sb.AppendLine("#include <limits.h>");
        sb.AppendLine("#include <float.h>");
        sb.AppendLine("#include <math.h>");
        sb.AppendLine();
        sb.AppendLine("typedef void (*Action)(void*);");
        sb.AppendLine("typedef void (*Action_t)(void);");
        sb.AppendLine();
        sb.AppendLine("typedef struct Control    Control;");
        sb.AppendLine("typedef struct Form       Form;");
        sb.AppendLine("typedef struct Label      Label;");
        sb.AppendLine("typedef struct Button     Button;");
        sb.AppendLine("typedef struct ProgressBar ProgressBar;");
        sb.AppendLine("typedef struct SwitchApp  SwitchApp;");
        sb.AppendLine();
        sb.AppendLine("#include \"switchapp.h\"");
        sb.AppendLine();
        sb.AppendLine("extern char _cs2sx_strbuf[1024];");
        sb.AppendLine();

        var alreadyDeclared = new HashSet<string>(StringComparer.Ordinal)
        {
            "Control", "Form", "Label", "Button", "ProgressBar", "SwitchApp",
        };

        foreach (var csFile in sourceFiles)
        {
            var source = System.IO.File.ReadAllText(csFile);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            foreach (var typeDecl in tree.GetRoot()
                .DescendantNodes()
                .Where(n => n is ClassDeclarationSyntax or StructDeclarationSyntax))
            {
                if (typeDecl is ClassDeclarationSyntax cls
                    && cls.TypeParameterList?.Parameters.Count > 0)
                    continue;

                var typeName = typeDecl is ClassDeclarationSyntax c
                    ? c.Identifier.Text
                    : ((StructDeclarationSyntax)typeDecl).Identifier.Text;

                if (alreadyDeclared.Add(typeName))
                    sb.AppendLine($"typedef struct {typeName} {typeName};");

                // Also forward-declare the vtable struct for classes with virtual methods
                if (typeDecl is ClassDeclarationSyntax clsWithVirtuals
                    && Transpiler.VTableBuilder.HasVirtualMethods(clsWithVirtuals))
                    sb.AppendLine($"typedef struct {typeName}_vtable {typeName}_vtable;");
            }
        }

        if (expandedTypeNames != null)
        {
            var hadAny = false;
            foreach (var expandedName in expandedTypeNames)
            {
                if (!alreadyDeclared.Add(expandedName)) continue;
                if (!hadAny)
                {
                    sb.AppendLine();
                    sb.AppendLine("// Expanded generic types (from _generics.h)");
                    hadAny = true;
                }
                sb.AppendLine($"typedef struct {expandedName} {expandedName};");
            }
        }

        // Emit typedefs for Action<T> delegate types found in source files.
        // e.g. Action<Window> → typedef void (*Action_Window_t)(Window*);
        var emittedDelegateTypedefs = new HashSet<string>(StringComparer.Ordinal);
        foreach (var csFile in sourceFiles)
        {
            var source = System.IO.File.ReadAllText(csFile);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            foreach (var typeNode in tree.GetRoot()
                .DescendantNodes()
                .OfType<Microsoft.CodeAnalysis.CSharp.Syntax.GenericNameSyntax>()
                .Where(g => g.Identifier.Text == "Action"))
            {
                var csType = typeNode.ToString().Trim();
                if (!csType.StartsWith("Action<") || !csType.EndsWith(">")) continue;

                var cName = CS2SX.Core.TypeRegistry.MapType(csType);
                if (!cName.EndsWith("_t") || !emittedDelegateTypedefs.Add(cName)) continue;

                var inner = csType[7..^1].Trim();
                // Build the C parameter list: each type arg becomes its mapped C type + * if reference
                var typeArgs = SplitSimpleGenericArgs(inner);
                var cParams = string.Join(", ", typeArgs.Select(a =>
                {
                    a = a.Trim();
                    var mapped = CS2SX.Core.TypeRegistry.MapType(a);
                    if (!mapped.EndsWith("*") && CS2SX.Transpiler.CSharpToC.NeedsPtr(a))
                        mapped += "*";
                    return mapped;
                }));
                sb.AppendLine($"typedef void (*{cName})({cParams});");
            }
        }

        // FIX: Custom-Header aus dem Projektverzeichnis anhängen.
        // _forward.h wird von JEDEM generierten .h includiert → Custom-Funktionen
        // (z.B. Freetype_FT_Init_FreeType aus freetype_main.h) sind damit in
        // jeder Translation Unit sichtbar ohne manuelles #include.
        var customHeaders = Directory
            .GetFiles(_projectDir, "*.h")
            .Select(Path.GetFileName)
            .OrderBy(n => n)
            .ToList();

        if (customHeaders.Count > 0)
        {
            sb.AppendLine();
            sb.AppendLine("// Custom project headers");
            foreach (var ch in customHeaders)
            {
                if (listUserClassTypes != null && ch != null && IsListOnlyHeader(ch, listUserClassTypes))
                {
                    Log.Warning($"Skipping '{ch}' — defines List<UserClass> types that are now auto-generated in _generics.h. Remove this file from your project.");
                    continue;
                }
                sb.AppendLine($"#include \"{ch}\"");
            }
        }

        System.IO.File.WriteAllText(outputPath, sb.ToString());
    }


    private static readonly HashSet<string> s_builtinBaseTypes = new(StringComparer.Ordinal)
    {
        "Control", "Form", "Label", "Button", "ProgressBar", "SwitchApp",
        "SwitchAppEx", "object", "Object",
    };

    /// <summary>
    /// If the source contains a class that derives from a user-defined (transpiled) base,
    /// returns "#include "BaseClass.h"\n"; otherwise returns empty string.
    /// </summary>
    private static string GetUserDefinedBaseInclude(string source, IReadOnlyList<string> transpiledFiles)
    {
        try
        {
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            var cls = tree.GetRoot().DescendantNodes()
                .OfType<ClassDeclarationSyntax>()
                .FirstOrDefault(c => c.BaseList?.Types.Any() == true);
            if (cls == null) return "";

            var baseTypeSyntax = cls.BaseList!.Types.First().Type.ToString().Trim();
            var baseName = baseTypeSyntax.Split('<')[0].Trim();

            if (s_builtinBaseTypes.Contains(baseName)) return "";

            // Only include if the base type is one of the transpiled user files
            var transpiledNames = transpiledFiles
                .Select(f => Path.GetFileNameWithoutExtension(f));
            if (!transpiledNames.Contains(baseName, StringComparer.Ordinal)) return "";

            return $"#include \"{baseName}.h\"\n";
        }
        catch { return ""; }
    }

    private static List<string> SplitSimpleGenericArgs(string s)
    {
        var result = new List<string>();
        int depth = 0, start = 0;
        for (int i = 0; i < s.Length; i++)
        {
            if (s[i] == '<') depth++;
            else if (s[i] == '>') depth--;
            else if (s[i] == ',' && depth == 0)
            {
                result.Add(s.Substring(start, i - start));
                start = i + 1;
            }
        }
        if (start < s.Length) result.Add(s.Substring(start));
        return result;
    }

    private static string WrapHeader(string baseName, string content)
    {
        var guard = "CS2SX_" + baseName.ToUpperInvariant() + "_H";
        return "#pragma once\n"
             + "#ifndef " + guard + "\n"
             + "#define " + guard + "\n\n"
             + content
             + "\n\n#endif\n";
    }

    private static string? FindSwitchAppClass(IReadOnlyList<string> sourceFiles)
    {
        foreach (var file in sourceFiles)
        {
            var source = System.IO.File.ReadAllText(file);
            var tree = Microsoft.CodeAnalysis.CSharp.CSharpSyntaxTree.ParseText(source);
            foreach (var cls in tree.GetRoot()
                .DescendantNodes().OfType<ClassDeclarationSyntax>())
                if (cls.BaseList?.Types.FirstOrDefault()?.ToString().Trim() == "SwitchApp")
                    return cls.Identifier.Text;
        }
        return null;
    }

    private static string? FindHeaderForClass(
        IReadOnlyList<string> sourceFiles, string className)
    {
        foreach (var file in sourceFiles)
            if (System.IO.File.ReadAllText(file).Contains("class " + className))
                return Path.GetFileNameWithoutExtension(file) + ".h";
        return null;
    }

